def real_style_world(tmp_path):
    """三个项目：p 有 14 份（每份随机拼 3 篇），q、r 各 6 份；p 有两场会，其中两次把司美格鲁肽听成司美格鲁太。"""
    rng = random.Random(3)
    db = make_db(tmp_path)
    add_project(db, "p", "云图")
    add_project(db, "q", "北辰仓")
    add_project(db, "r", "数据中台")
    roots = {
        pid: add_root(db, pid, tmp_path / name)
        for pid, name in (("p", "云图目录"), ("q", "北辰目录"), ("r", "中台目录"))
    }
    number = 0
    for pid, docs, count in (("p", P_DOCS, 14), ("q", Q_DOCS, 6), ("r", R_DOCS, 6)):
        for index in range(count):
            number += 1
            text = "\n".join(rng.sample(docs, min(3, len(docs))))
            add_content(
                db, f"k{number}", [text[start : start + 500] for start in range(0, len(text), 500)]
            )
            add_file(db, roots[pid], f"文档{index}.docx", key=f"k{number}")
    add_meeting(
        db,
        "m1",
        date="2026-09-20T10:00:00",
        project_id="p",
        segments=[
            "今天主要讨论一下初审规则的问题",
            "司美格鲁太的冷链运输北辰那边负责",
            "受试者用药记录要支持导出",
            "药房管理员培训放在上线前",
            "初审规则先按纸质流程",
            "司美格鲁太的温度要求是2到8度",
            "药品追溯码的格式",
        ],
    )
    add_meeting(
        db,
        "m2",
        date="2026-09-26T10:00:00",
        project_id="p",
        segments=[
            "北辰科研仓的接口文档还没确认",
            "药品追溯码的格式他们提供",
            "受试者用药记录的导出下周做",
            "冷链温度报警要测",
        ],
    )
    return db
